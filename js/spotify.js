// Check history listening events
async function pollListeningHistory() {
    // do nothing if its currently checking already
    if (checkingHistory) return;

    checkingHistory = true;

    try {
        await checkForListeningEvents();
    } catch (error) {
        console.error("History monitoring error:", error);
    } finally {
        checkingHistory = false;
    }
}

// Begin history check and check every 30 sec
function startHistoryMonitoring() {
    if (historyMonitoringInterval !== null) return;

    console.log("Starting listening history monitoring...");

    pollListeningHistory();

    // Check every 30 seconds
    historyMonitoringInterval = setInterval(
        pollListeningHistory,
        30000
    );
}

// Cease history checking
function stopHistoryMonitoring() {
    if (historyMonitoringInterval !== null) {
        clearInterval(historyMonitoringInterval);
        historyMonitoringInterval = null;
    }

    console.log("Listening history monitoring stopped.");
}


