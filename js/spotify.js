// Helper function to standardize data format
function formatSpotifyTrack(track) {
    return {
        id: track.id,
        title: track.name,
        artist: track.artists.map(a => a.name).join(", "),
        album: track.album.name,
        albumArt: track.album.images[0]?.url ?? null,
        spotifyUrl: track.external_urls.spotify,
        explicit: track.explicit
    };
}

// Helper to track if the same song is listened to multiple times
function formatListeningEvent(entry) {
    const track = formatSpotifyTrack(entry.track);

    return {
        ...track,

        // Unique identifier for this playback event
        eventId: `${track.id}_${entry.played_at}`,

        // Timestamp supplied by Spotify
        playedAt: entry.played_at
    };
}

// Generate a secure random PKCE verifier
// (essentially creating a secret for the OAuth request)
function generateRandomString(length) {
    const characters =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-._~";

    const bytes = new Uint8Array(length);
    crypto.getRandomValues(bytes);

    return Array.from(bytes, byte =>
        characters[byte % characters.length]
    ).join("");
}

// Generate the SHA-256 challenge
// (compares the PKCE secret to prevent data tampering)
async function generateCodeChallenge(verifier) {
    const data = new TextEncoder().encode(verifier);
    const digest = await crypto.subtle.digest("SHA-256", data);

    return btoa(String.fromCharCode(...new Uint8Array(digest)))
        .replace(/\+/g, "-")
        .replace(/\//g, "_")
        .replace(/=+$/, "");
}

// Start Spotify login
// Uses the secrets generated by helper functions to verify with spotify and log in a user
async function login() {
    const verifier = generateRandomString(64);
    const challenge = await generateCodeChallenge(verifier);
    const state = generateRandomString(32);

    sessionStorage.setItem("spotify_verifier", verifier);
    sessionStorage.setItem("spotify_state", state);

    const params = new URLSearchParams({
        client_id: CLIENT_ID,
        response_type: "code",
        redirect_uri: REDIRECT_URI,
        scope: SCOPES.join(" "),
        code_challenge_method: "S256",
        code_challenge: challenge,
        state: state
    });

    window.location.href =
        "https://accounts.spotify.com/authorize?" + params;
}

// Refreshes access token if expired
async function refreshSpotifyToken() {
    // Prevent multiple simultaneous refresh requests.
    if (refreshPromise) {
        return refreshPromise;
    }

    refreshPromise = (async () => {
        const refreshToken = sessionStorage.getItem(
            "spotify_refresh_token"
        );

        if (!refreshToken) {
            throw new Error(
                "No refresh token available. Please log in again."
            );
        }

        const response = await fetch(
            "https://accounts.spotify.com/api/token",
            {
                method: "POST",
                headers: {
                    "Content-Type":
                        "application/x-www-form-urlencoded"
                },
                body: new URLSearchParams({
                    grant_type: "refresh_token",
                    refresh_token: refreshToken,
                    client_id: CLIENT_ID
                })
            }
        );

        const data = await response.json();

        if (!response.ok) {
            throw new Error(
                "Spotify token refresh failed: " +
                JSON.stringify(data)
            );
        }

        saveSpotifyTokens(data);

        return data.access_token;
    })();

    try {
        return await refreshPromise;
    } finally {
        refreshPromise = null;
    }
}

// Helper for saving tokens and refreshing automatically to prevent 1 hour timeouts
function saveSpotifyTokens(data) {
    // Store access token
    sessionStorage.setItem(
        "spotify_access_token",
        data.access_token
    );

    // Spotify may rotate the refresh token.
    // Keep the existing one if no new token is provided.
    if (data.refresh_token) {
        sessionStorage.setItem(
            "spotify_refresh_token",
            data.refresh_token
        );
    }

    // Save the time at which the access token expires.
    const expiresAt = Date.now() + data.expires_in * 1000;

    sessionStorage.setItem(
        "spotify_expires_at",
        expiresAt.toString()
    );

    console.log("Spotify tokens updated.");
}

// Gets current token and refreshes before expiration
async function getValidAccessToken() {
    const token = sessionStorage.getItem(
        "spotify_access_token"
    );

    const expiresAt = Number(
        sessionStorage.getItem("spotify_expires_at")
    );

    // Refresh 60 seconds before expiration.
    const needsRefresh =
        !token ||
        !expiresAt ||
        Date.now() >= expiresAt - 60000;

    if (needsRefresh) {
        return await refreshSpotifyToken();
    }

    return token;
}


// Exchange authorization code for access token
// Note: using session storage currently which is not as secure as token storage should be for a deployed project
async function handleCallback() {
    const params = new URLSearchParams(window.location.search);

    const error = params.get("error");
    if (error) throw new Error("Spotify authorization: " + error);

    const code = params.get("code");
    if (!code) return;

    const state = params.get("state");
    const expectedState = sessionStorage.getItem("spotify_state");

    if (!expectedState || state !== expectedState) {
        throw new Error("Invalid authorization state");
    }

    const verifier = sessionStorage.getItem("spotify_verifier");
    if (!verifier) throw new Error("Missing PKCE verifier");

    const response = await fetch(
        "https://accounts.spotify.com/api/token",
        {
            method: "POST",
            headers: {
                "Content-Type": "application/x-www-form-urlencoded"
            },
            body: new URLSearchParams({
                client_id: CLIENT_ID,
                grant_type: "authorization_code",
                code: code,
                redirect_uri: REDIRECT_URI,
                code_verifier: verifier
            })
        }
    );

    const data = await response.json();

    if (!response.ok) {
        throw new Error(JSON.stringify(data));
    }

    saveSpotifyTokens(data);

    sessionStorage.removeItem("spotify_verifier");
    sessionStorage.removeItem("spotify_state");

    display("Successfully connected to Spotify!");

    // Return to the main test page
    window.location.replace("index.html");
}

// Make an authenticated Spotify request
// Helper function that accepts an endpoint and queries the Spotify API
async function spotifyRequest(endpoint) {
    // Ensures access token is valid for request
    let token = await getValidAccessToken();

    let response = await fetch(
        "https://api.spotify.com/v1" + endpoint,
        {
            headers: {
                Authorization: "Bearer " + token
            }
        }
    );

    // If Spotify rejects the token, refresh and retry once.
    if (response.status === 401) {
        token = await refreshSpotifyToken();

        response = await fetch(
            "https://api.spotify.com/v1" + endpoint,
            {
                headers: {
                    Authorization: "Bearer " + token
                }
            }
        );
    }

    // If it returns OK status, continue
    if (response.status === 204) {
        return null;
    }

    // If it returns an error, throw and display error
    if (!response.ok) {
        throw new Error(
            "Spotify API error: " +
            response.status + " " +
            await response.text()
        );
    }

    return response.json();
}


